function createOrderer() {
  infoln "Enrolling the CA admin"
  mkdir -p organizations/ordererOrganizations/clearchain.com

  export FABRIC_CA_CLIENT_HOME=${PWD}/organizations/ordererOrganizations/clearchain.com

  set -x
  fabric-ca-client enroll -u https://admin:adminpw@localhost:9054 --caname ca-orderer --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
  { set +x; } 2>/dev/null

  echo 'NodeOUs:
  Enable: true
  ClientOUIdentifier:
    Certificate: cacerts/localhost-9054-ca-orderer.pem
    OrganizationalUnitIdentifier: client
  PeerOUIdentifier:
    Certificate: cacerts/localhost-9054-ca-orderer.pem
    OrganizationalUnitIdentifier: peer
  AdminOUIdentifier:
    Certificate: cacerts/localhost-9054-ca-orderer.pem
    OrganizationalUnitIdentifier: admin
  OrdererOUIdentifier:
    Certificate: cacerts/localhost-9054-ca-orderer.pem
    OrganizationalUnitIdentifier: orderer' > "${PWD}/organizations/ordererOrganizations/clearchain.com/msp/config.yaml"

  # Since the CA serves as both the organization CA and TLS CA, copy the org's root cert that was generated by CA startup into the org level ca and tlsca directories

  # Copy orderer org's CA cert to orderer org's /msp/tlscacerts directory (for use in the channel MSP definition)
  mkdir -p "${PWD}/organizations/ordererOrganizations/clearchain.com/msp/tlscacerts"
  cp "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem" "${PWD}/organizations/ordererOrganizations/clearchain.com/msp/tlscacerts/tlsca.clearchain.com-cert.pem"

  # Copy orderer org's CA cert to orderer org's /tlsca directory (for use by clients)
  mkdir -p "${PWD}/organizations/ordererOrganizations/clearchain.com/tlsca"
  cp "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem" "${PWD}/organizations/ordererOrganizations/clearchain.com/tlsca/tlsca.clearchain.com-cert.pem"

# Loop through each orderer (orderer, orderer2, orderer3, orderer4) to register and generate artifacts
  for ORDERER in orderer orderer2 orderer3 orderer4; do
    infoln "Registering ${ORDERER}"
    set -x
    fabric-ca-client register --caname ca-orderer --id.name ${ORDERER} --id.secret ${ORDERER}pw --id.type orderer --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
    { set +x; } 2>/dev/null

    infoln "Generating the ${ORDERER} MSP"
    set -x
    fabric-ca-client enroll -u https://${ORDERER}:${ORDERER}pw@localhost:9054 --caname ca-orderer -M "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
    { set +x; } 2>/dev/null

    cp "${PWD}/organizations/ordererOrganizations/clearchain.com/msp/config.yaml" "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp/config.yaml"

    # Workaround: Rename the signcert file to ensure consistency with Cryptogen generated artifacts
    mv "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp/signcerts/cert.pem" "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp/signcerts/${ORDERER}.clearchain.com-cert.pem"

    infoln "Generating the ${ORDERER} TLS certificates, use --csr.hosts to specify Subject Alternative Names"
    set -x
    fabric-ca-client enroll -u https://${ORDERER}:${ORDERER}pw@localhost:9054 --caname ca-orderer -M "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls" --enrollment.profile tls --csr.hosts ${ORDERER}.clearchain.com --csr.hosts localhost --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
    { set +x; } 2>/dev/null

    # Copy the tls CA cert, server cert, server keystore to well known file names in the orderer's tls directory that are referenced by orderer startup config
    cp "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/tlscacerts/"* "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/ca.crt"
    cp "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/signcerts/"* "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/server.crt"
    cp "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/keystore/"* "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/server.key"

    # Copy orderer org's CA cert to orderer's /msp/tlscacerts directory (for use in the orderer MSP definition)
    mkdir -p "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp/tlscacerts"
    cp "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/tls/tlscacerts/"* "${PWD}/organizations/ordererOrganizations/clearchain.com/orderers/${ORDERER}.clearchain.com/msp/tlscacerts/tlsca.clearchain.com-cert.pem"
  done

  # Register and generate artifacts for the orderer admin
  infoln "Registering the orderer admin"
  set -x
  fabric-ca-client register --caname ca-orderer --id.name ordererAdmin --id.secret ordererAdminpw --id.type admin --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Generating the admin msp"
  set -x
  fabric-ca-client enroll -u https://ordererAdmin:ordererAdminpw@localhost:9054 --caname ca-orderer -M "${PWD}/organizations/ordererOrganizations/clearchain.com/users/Admin@clearchain.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/ordererOrg/ca-cert.pem"
  { set +x; } 2>/dev/null

  cp "${PWD}/organizations/ordererOrganizations/clearchain.com/msp/config.yaml" "${PWD}/organizations/ordererOrganizations/clearchain.com/users/Admin@clearchain.com/msp/config.yaml"
}
