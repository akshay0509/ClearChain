  # cp "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer1.switch.clearchain.com/tls/keystore/"* "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/server.key"

