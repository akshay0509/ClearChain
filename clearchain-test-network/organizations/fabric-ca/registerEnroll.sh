#!/usr/bin/env bash

function createSwitch() {
  infoln "Enrolling the CA admin"
  mkdir -p organizations/peerOrganizations/switch.clearchain.com/

  export FABRIC_CA_CLIENT_HOME=${PWD}/organizations/peerOrganizations/switch.clearchain.com/

  set -x
  fabric-ca-client enroll -u https://admin:adminpw@localhost:7054 --caname ca-switch --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

  echo 'NodeOUs:
  Enable: true
  ClientOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-switch.pem
    OrganizationalUnitIdentifier: client
  PeerOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-switch.pem
    OrganizationalUnitIdentifier: peer
  AdminOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-switch.pem
    OrganizationalUnitIdentifier: admin
  OrdererOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-switch.pem
    OrganizationalUnitIdentifier: orderer' > "${PWD}/organizations/peerOrganizations/switch.clearchain.com/msp/config.yaml"

  # Since the CA serves as both the organization CA and TLS CA, copy the org's root cert that was generated by CA startup into the org level ca and tlsca directories

  # Copy switch's CA cert to switch's /msp/tlscacerts directory (for use in the channel MSP definition)
  mkdir -p "${PWD}/organizations/peerOrganizations/switch.clearchain.com/msp/tlscacerts"
  cp "${PWD}/organizations/fabric-ca/switch/ca-cert.pem" "${PWD}/organizations/peerOrganizations/switch.clearchain.com/msp/tlscacerts/ca.crt"

  # Copy switch's CA cert to switch's /tlsca directory (for use by clients)
  mkdir -p "${PWD}/organizations/peerOrganizations/switch.clearchain.com/tlsca"
  cp "${PWD}/organizations/fabric-ca/switch/ca-cert.pem" "${PWD}/organizations/peerOrganizations/switch.clearchain.com/tlsca/tlsca.switch.clearchain.com-cert.pem"

  # Copy switch's CA cert to switch's /ca directory (for use by clients)
  mkdir -p "${PWD}/organizations/peerOrganizations/switch.clearchain.com/ca"
  cp "${PWD}/organizations/fabric-ca/switch/ca-cert.pem" "${PWD}/organizations/peerOrganizations/switch.clearchain.com/ca/ca.switch.clearchain.com-cert.pem"

  infoln "Registering peer0"
  set -x
  fabric-ca-client register --caname ca-switch --id.name peer0 --id.secret peer0pw --id.type peer --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Registering user"
  set -x
  fabric-ca-client register --caname ca-switch --id.name user1 --id.secret user1pw --id.type client --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Registering the org admin"
  set -x
  fabric-ca-client register --caname ca-switch --id.name switchadmin --id.secret switchadminpw --id.type admin --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Generating the peer0 msp"
  set -x
  fabric-ca-client enroll -u https://peer0:peer0pw@localhost:7054 --caname ca-switch -M "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

  cp "${PWD}/organizations/peerOrganizations/switch.clearchain.com/msp/config.yaml" "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/msp/config.yaml"

  infoln "Generating the peer0-tls certificates, use --csr.hosts to specify Subject Alternative Names"
  set -x
  fabric-ca-client enroll -u https://peer0:peer0pw@localhost:7054 --caname ca-switch -M "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls" --enrollment.profile tls --csr.hosts peer0.switch.clearchain.com --csr.hosts localhost --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null

# copy the tls certs to peer0 directory
  cp "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/tlscacerts/"* "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/ca.crt"
  cp "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/signcerts/"* "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/server.crt"
  cp "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/keystore/"* "${PWD}/organizations/peerOrganizations/switch.clearchain.com/peers/peer0.switch.clearchain.com/tls/server.key"

## generating peer1 certs

  infoln "Registering peer1"
  set -x
  fabric-ca-client register --caname ca-switch --id.name peer1 --id.secret peer1pw --id.type peer --tls.certfiles "${PWD}/organizations/fabric-ca/switch/ca-cert.pem"
  { set +x; } 2>/dev/null


  infoln "Generating the peer1 msp"
